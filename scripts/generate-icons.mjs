// Copies the Phosphor icon shapes we use into src/components/ui/icon-defs.tsx.
// Run after changing the name map in src/components/ui/icons.tsx:  node scripts/generate-icons.mjs
// Phosphor Icons (MIT) - https://phosphoricons.com. Only regular, bold, fill and duotone are kept.
import { readFileSync, writeFileSync } from 'node:fs';

const iconsFile = 'src/components/ui/icons.tsx';
const src = readFileSync(iconsFile, 'utf8');
const names = [...new Set([...src.matchAll(/make\(P\.(\w+),/g)].map((m) => m[1]))].sort();
const KEEP = new Set(['regular', 'bold', 'fill', 'duotone']);

let out = `/* GENERATED by scripts/generate-icons.mjs from phosphor-react-native (MIT). Do not edit. */
import React, { type ReactElement, type FC } from 'react';
import { Path, Circle, Line, Polyline, Polygon, Rect, Ellipse } from 'react-native-svg';

export type IconWeight = 'regular' | 'bold' | 'fill' | 'duotone';
export type DuotoneFn = FC<{ duotoneColor?: string; duotoneOpacity?: number }>;
export type IconDef = Map<IconWeight, ReactElement | DuotoneFn>;

// Keep every svg primitive referenced so unused-import lint stays quiet.
void [React, Path, Circle, Line, Polyline, Polygon, Rect, Ellipse];

`;
for (const n of names) {
  const file = readFileSync(`node_modules/phosphor-react-native/src/defs/${n}.tsx`, 'utf8');
  const body = file.slice(file.indexOf('export default new Map'));
  // Split the array of [weight, element] entries and keep the weights we use.
  const start = body.indexOf('([') + 2;
  const end = body.lastIndexOf('])');
  const inner = body.slice(start, end);
  const entries = [];
  let depth = 0, cur = '', i = 0;
  for (; i < inner.length; i++) {
    const c = inner[i];
    if (c === '[' && depth === 0) { cur = ''; depth = 1; continue; }
    if (c === '[' || c === '(' || c === '{') depth++;
    if (c === ']' || c === ')' || c === '}') depth--;
    if (depth === 0 && c === ']') { entries.push(cur); cur = ''; continue; }
    if (depth >= 1) cur += c;
  }
  const kept = entries.filter((e) => KEEP.has((e.match(/'(\w+)'/) || [])[1]));
  out += `export const ${n}: IconDef = new Map<IconWeight, ReactElement | DuotoneFn>([\n${kept.map((e) => `  [${e.trim()}]`).join(',\n')},\n]);\n\n`;
}
writeFileSync('src/components/ui/icon-defs.tsx', out);
console.log(`icon-defs: ${names.length} icons`);
